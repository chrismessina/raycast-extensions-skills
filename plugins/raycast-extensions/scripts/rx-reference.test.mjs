test("R2-2 loadRegistryDocument accepts registry data only from exit 0 with a consistent envelope", async () => {
  await withTempDir(async (dir) => {
    const commands = [{ name: "doctor", flags: { ...GLOBAL }, subcommands: {} }];
    const ok = { command: "commands", version: "0.1.0", exit: 0, data: { commands }, results: [{ id: "commands", verdict: "PASS", message: "1 command" }] };
    // A fake rx checkout (RX_DEV) whose `commands --json` prints `doc` and exits `code`; no network.
    const fake = (/** @type {object} */ doc, /** @type {number} */ code) => {
      const root = mkdtempSync(join(dir, "rx-"));
      mkdirSync(join(root, "bin"));
      writeFileSync(join(root, "bin", "rx.mjs"), `process.stdout.write(${JSON.stringify(JSON.stringify(doc))});\nprocess.exitCode = ${code};\n`);
      return { ...process.env, RX_DEV: root, RX_TARBALL: "" };
    };
    assert.equal((await loadRegistryDocument({ env: fake(ok, 0) })).commands[0].name, "doctor");
    // Codex round-2 probe: the child exits 2 while its JSON claims exit 0.
    await assert.rejects(loadRegistryDocument({ env: fake(ok, 2) }), /exited 2 but its envelope says exit 0/);
    await assert.rejects(loadRegistryDocument({ env: fake({ ...ok, exit: 1 }, 0) }), /exited 0 but its envelope says exit 1/);
    await assert.rejects(loadRegistryDocument({ env: fake({ ...ok, results: [{ id: "commands", verdict: "FAIL", message: "x" }] }, 0) }), /verdicts imply 1/);
    await assert.rejects(loadRegistryDocument({ env: fake({ ...ok, exit: 1, results: [{ id: "commands", verdict: "FAIL", message: "x" }] }, 1) }), /exit 1/);
    // A saved document is held to the same envelope rules (as if rx had exited 0).
    const f = join(dir, "saved.json");
    writeFileSync(f, JSON.stringify({ ...ok, results: [{ id: "commands", verdict: "ERROR", message: "x" }] }));
    await assert.rejects(loadRegistryDocument({ registryFile: f }), /verdicts imply 2/);
  });
});

test("R3-2 loadRegistryDocument requires exactly one `commands` result, verdict PASS", async () => {
  await withTempDir(async (dir) => {
    const commands = [{ name: "doctor", flags: { ...GLOBAL }, subcommands: {} }];
    const doc = (/** @type {object[]} */ results) => ({ command: "commands", version: "0.1.0", exit: 0, data: { commands }, results });
    const f = join(dir, "saved.json");
    const load = (/** @type {object[]} */ results) => {
      writeFileSync(f, JSON.stringify(doc(results)));
      return loadRegistryDocument({ registryFile: f });
    };
    assert.equal((await load([{ id: "commands", verdict: "PASS", message: "1 command" }])).commands.length, 1);
    await assert.rejects(load([]), /exactly one `commands` result/);
    await assert.rejects(load([{ id: "other", verdict: "PASS", message: "" }]), /exactly one `commands` result/);
    await assert.rejects(load([{ id: "commands", verdict: "WARN", message: "" }]), /exactly one `commands` result/);
    await assert.rejects(load([{ id: "commands", verdict: "PASS", message: "" }, { id: "commands", verdict: "PASS", message: "" }]), /exactly one `commands` result/);
  });
});
